"""Tests for Qiskit Aer QAOA Solver, Circuit Metrics, and Simulation Limits.

Verifies:
1. QAOA executes genuinely using Qiskit Aer statevector/sampler with p-layer ansatz.
2. Quantum circuit resource metrics (depth, two-qubit gates, total gates, parameters) are measured.
3. Simulation guard blocks instances exceeding max_sim_qubits (24 qubits) with structured status.
4. QAOA decodes using the common pipeline decoder.
"""

import numpy as np
from evcore.qubo import QUBOModel
from evcore.qaoa_solver import QAOASolver, QAOA_DEFAULT_SIMULATION_LIMIT
from evcore.decoder import decode_solution

SMALL_INSTANCE_6Q = {
    "id": "qaoa-test-6q",
    "name": "6-Qubit Test Instance",
    "n_ev": 2,
    "n_st": 2,
    "n_t": 2,
    "demand": [1, 1],
    "window": [[0], [1]],
    "price": [2.0, 5.0],
    "grid_cap": [1, 1],
    "open_cost": [10.0, 0.5],
    "detour": [[0.0, 10.0], [10.0, 0.0]],
    "stress_w": 0.25,
    "seed": 42,
}


def test_qaoa_solver_execution_and_metrics():
    """Verifies that QAOA executes on Aer and measures genuine quantum circuit resources."""
    model = QUBOModel(SMALL_INSTANCE_6Q)
    assert model.n_vars == 6

    solver = QAOASolver(
        p=1,
        shots=128,
        optimizer="COBYLA",
        max_iterations=10,
        seed=42,
        max_sim_qubits=24,
    )
    result = solver.solve(model)

    assert result["status"] == "completed"
    assert result["resources"]["qubits"] == 6
    assert len(result["best_bitstring"]) == 6
    assert result["metrics"]["evaluations"] > 0
    assert result["metrics"]["shots"] == 128
    assert result["parameters"]["p"] == 1
    assert result["parameters"]["optimizer"] == "COBYLA"

    # Circuit resources
    cr = result["resources"]
    assert cr["qubits"] == 6
    assert cr["depth"] > 0
    assert cr["total_gates"] > 0
    assert cr["two_qubit_gates"] > 0
    assert cr["transpiled_depth"] > 0
    assert result["parameters"]["p"] * 2 == 2  # 2*p = 2 parameters

    # Verify decoding
    decoded = decode_solution(result["best_bitstring"], model)
    assert "objective" in decoded
    assert "cost_breakdown" in decoded
    assert "schedule" in decoded


def test_qaoa_simulation_guard_over_limit():
    """Verifies that instances with > max_sim_qubits return clean unsupported_size status."""
    class DummyLargeQUBO:
        def __init__(self, n):
            self.n_vars = n
            self.Q_sym = np.zeros((n, n))
            self.offset = 0.0
        def to_ising(self):
            return np.zeros((self.n_vars, self.n_vars)), np.zeros(self.n_vars), 0.0

    large_model = DummyLargeQUBO(25)
    solver = QAOASolver(max_sim_qubits=24)
    result = solver.solve(large_model)

    assert result["status"] == "unsupported_size"
    assert "simulation limit exceeded" in result["reason"].lower()
    assert result["actual_qubits"] == 25
    assert result["maximum_simulation_qubits"] == 24
    assert "exceeds" in result["message"] or "exceeding" in result["message"]


def test_cost_hamiltonian_unitary_circuit_equivalence():
    """Verifies that U_C(gamma) generated by the circuit matches exp(-i gamma H_C) within machine precision."""
    from qiskit import QuantumCircuit
    from qiskit.quantum_info import Operator

    # 3-qubit QUBO with non-zero off-diagonals
    Q = np.array([
        [2.0, -1.5,  0.8],
        [0.0,  3.0, -2.1],
        [0.0,  0.0,  1.7]
    ])
    Q_sym = 0.5 * (Q + Q.T)
    offset = 2.2
    gamma = 0.43

    J = 0.25 * Q_sym.copy()
    np.fill_diagonal(J, 0.0)
    h = -0.5 * np.sum(Q_sym, axis=1)
    c_ising = float(offset + 0.25 * np.sum(Q_sym) + 0.25 * np.trace(Q_sym))

    # Exact diagonal unitary in computational basis
    E_diag = []
    for idx in range(8):
        q0 = (idx >> 0) & 1
        q1 = (idx >> 1) & 1
        q2 = (idx >> 2) & 1
        z = np.array([q0, q1, q2], dtype=float)
        E_diag.append(float(z @ Q @ z + offset))

    U_exact = np.diag([np.exp(-1j * gamma * E) for E in E_diag])

    # Circuit implementation as in QAOASolver
    qc = QuantumCircuit(3)
    for i in range(3):
        for j in range(i + 1, 3):
            if abs(J[i, j]) > 1e-6:
                qc.rzz(4.0 * gamma * J[i, j], i, j)
        if abs(h[i]) > 1e-6:
            qc.rz(2.0 * gamma * h[i], i)

    U_circuit = Operator(qc).data
    phase_factor = np.exp(-1j * gamma * c_ising)
    U_scaled = U_circuit * phase_factor

    max_diff = np.max(np.abs(U_exact - U_scaled))
    assert max_diff < 1e-12, f"Unitary discrepancy: {max_diff}"


def test_qaoa_computational_basis_bitstring_ordering():
    """Verifies that reversed Qiskit measurement string maps qubit i to decoded bit i."""
    from qiskit import QuantumCircuit
    from qiskit_aer import AerSimulator

    qc = QuantumCircuit(4)
    qc.x(0)  # qubit 0 = 1
    qc.x(2)  # qubit 2 = 1
    # qubit 1 = 0, qubit 3 = 0
    qc.measure_all()

    sim = AerSimulator()
    counts = sim.run(qc, shots=50, seed_simulator=42).result().get_counts()
    raw_str = list(counts.keys())[0]

    # Qiskit reversed bit order mapping
    decoded_z = [int(c) for c in raw_str[::-1]]
    assert decoded_z == [1, 0, 1, 0], f"Bitstring mapping error: {decoded_z} != [1, 0, 1, 0]"

